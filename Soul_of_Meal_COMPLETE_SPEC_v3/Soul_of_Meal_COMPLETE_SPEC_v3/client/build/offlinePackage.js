import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';

export const OFFLINE_CACHE_PREFIX = 'soul-of-meal.practice.v1:';

export function writeOfflinePackage(output, workerSource) {
  const entries = [];
  const hdEntries = [];
  const splashFile = resolve(output, 'client/assets/splash/manifest.json');
  const splash = existsSync(splashFile) ? JSON.parse(readFileSync(splashFile, 'utf8')) : null;
  const hdFiles = new Set(splash?.hdFiles ?? []);
  const soundtrackFile = resolve(output, 'client/assets/audio/soundtracks.json');
  const soundtracks = existsSync(soundtrackFile)
    ? new Set(Object.values(JSON.parse(readFileSync(soundtrackFile, 'utf8'))).map(path => 'client/assets/audio/' + path)) : null;
  const dormantArt = ['avatars', 'portraits', 'cards', 'characters', 'golden'].map(directory => `client/assets/${directory}/`);
  function visit(directory) {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const path = resolve(directory, entry.name);
      if (entry.isDirectory()) visit(path);
      else {
        const name = relative(output, path).replaceAll('\\', '/');
        if (['client/offline-worker.js', 'client/offline-manifest.json'].includes(name)) continue;
        // Narration was removed; also reject it from imported legacy bundles.
        if (name.startsWith('client/assets/audio/voice/')) continue;
        if (splash?.coverage?.characters === 24 && name.startsWith('client/assets/original/showcase/')) continue;
        if (splash?.coverage?.cards >= 79 && name.startsWith('client/assets/original/cards/')) continue;
        // These are retained historical prototypes, not the original art/rigs
        // referenced by the current mobile runtime. Do not spend device quota on them.
        if (dormantArt.some(directory => name.startsWith(directory))) continue;
        if (soundtracks && name.startsWith('client/assets/audio/sound_track/') && name.endsWith('.mp3') && !soundtracks.has(name)) continue;
        const bytes = readFileSync(path);
        (hdFiles.has(name) ? hdEntries : entries).push({ url: relative(resolve(output, 'client'), path).replaceAll('\\', '/'),
          bytes: statSync(path).size, integrity: 'sha256-' + createHash('sha256').update(bytes).digest('base64') });
      }
    }
  }
  visit(output);
  entries.sort((a, b) => a.url.localeCompare(b.url, 'en'));
  hdEntries.sort((a, b) => a.url.localeCompare(b.url, 'en'));
  const worker = readFileSync(workerSource, 'utf8');
  const build = createHash('sha256').update(JSON.stringify({ entries, hdEntries })).update(worker).digest('hex');
  const manifest = { schema: 1, build, bytes: entries.reduce((sum, entry) => sum + entry.bytes, 0), entries,
    hdEntries, hdBytes: hdEntries.reduce((sum, entry) => sum + entry.bytes, 0) };
  writeFileSync(resolve(output, 'client/offline-manifest.json'), JSON.stringify(manifest));
  writeFileSync(resolve(output, 'client/offline-worker.js'),
    `/* Generated by the Vite offline package builder. */\nconst OFFLINE_PACKAGE = ${JSON.stringify(manifest)};\n` + worker);
  return manifest;
}
