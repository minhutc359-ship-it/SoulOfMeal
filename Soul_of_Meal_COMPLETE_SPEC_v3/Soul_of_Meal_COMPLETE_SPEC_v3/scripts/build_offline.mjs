import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve, relative } from "node:path";
const root = resolve(import.meta.dirname, ".."),
  client = resolve(root, "client");
async function walk(dir) {
  const files = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = resolve(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(path)));
    else files.push(path);
  }
  return files;
}
const selected = (await walk(client)).filter(
  (path) =>
    !path.includes("/tests/") &&
    !path.endsWith("offline-manifest.js") &&
    !path.endsWith(".py") &&
    !path.endsWith("gallery.html") &&
    !path.endsWith("package.json"),
);
for (const path of await walk(resolve(root, "examples")))
  if (path.endsWith(".json") && /\/(cards|auto_chess|maps)\//.test(path))
    selected.push(path);
const hash = createHash("sha256");
for (const path of selected.sort()) hash.update(await readFile(path));
const files = [
  "./",
  ...selected.map((path) => relative(client, path).split("\\").join("/")),
];
await writeFile(
  resolve(client, "offline-manifest.js"),
  `// Generated by node scripts/build_offline.mjs.\nself.SOUL_OFFLINE=${JSON.stringify({ version: hash.digest("hex").slice(0, 16), files }, null, 2)};\n`,
);
console.log(`Offline manifest: ${files.length} files.`);
